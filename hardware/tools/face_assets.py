#!/usr/bin/env python3
"""Deterministic expression JSON -> flash-resident C++ tables and manifest."""
from __future__ import annotations
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'service/data/global/deskbot-face.json'
OUTPUT = ROOT / 'hardware/firmware/generated'
sys.path.insert(0, str(ROOT / 'service/src'))
from deskbot_server.model.face_package import (  # noqa: E402
    compile_editor_document, encode_package, LAYERS as LAYERS, SHAPES as SHAPES, FIELDS as FIELDS,
)


def render_cpp(bundle):
    # Octal escapes safely represent UTF-8 and control bytes in C++ string literals.
    def quote(s):
        return '"' + ''.join(chr(b) if 32 <= b < 127 and b not in (34,92)
                             else f'\\{b:03o}' for b in s.encode('utf-8')) + '"'
    lines = ['// Generated by hardware/tools/face_assets.py. DO NOT EDIT.',
             f'static constexpr char kFaceAssetsVersion[] = "{bundle["version"]}";',
             f'static constexpr char kFaceClosedPhoneme[] = {quote(bundle["lipsync"]["closed_phoneme"])};',
             f'static constexpr char kFaceOpenPhoneme[] = {quote(bundle["lipsync"]["open_phoneme"])};',
             'static constexpr char kFaceIdleJson[] = '+quote(json.dumps(bundle['idle'],separators=(',',':')))+';',
             'static const FacePrimitive kFacePrimitives[] = {']
    for layer,shape,color,*rest in bundle['primitives']:
        vals,size,text = rest[:-2],rest[-2],rest[-1]
        lines.append('  {'+f'pb_anim_element_layer::{layer}, pb_anim_element_shape::{shape}, {color}, '+', '.join(map(str,vals))+f', {size}, '+(quote(text) if text else 'nullptr')+'},')
    lines += ['};','static const FaceFrame kFaceFrames[] = {']
    lines += [f'  {{{offset}, {count}, {ms}}},' for offset,count,ms in bundle['frames']]
    lines += ['};']
    for key, table in [('assets','kFaceEntries'),('phonemes','kPhonemeEntries')]:
        lines.append(f'static const FaceEntry {table}[] = {{')
        for asset in bundle[key]:
            for ident in [asset['id']]+asset['aliases']:
                lines.append('  {'+quote(ident)+f', {asset["frame_offset"]}, {asset["frame_count"]}, {asset["duration_ms"]}'+'},')
        lines.append('};')
    return '\n'.join(lines+[''])


def write_if_changed(path, text):
    if path.exists() and path.read_text(encoding='utf-8') == text:
        return
    path.parent.mkdir(parents=True,exist_ok=True)
    temporary = path.with_suffix(path.suffix+'.tmp')
    temporary.write_text(text, encoding='utf-8')
    temporary.replace(path)


def generate(source=SOURCE, output=OUTPUT, check=False):
    doc = json.loads(Path(source).read_text(encoding='utf-8'))
    bundle = compile_editor_document(doc)
    manifest = {k:bundle[k] for k in ('schema','version','assets','phonemes','lipsync','idle')}
    manifest['logical_size'] = [284,240]
    files = {'face_assets.inc':render_cpp(bundle), 'face_assets_manifest.json':json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',
             'face_package.json':encode_package(bundle).decode()}
    for filename,text in files.items():
        path = Path(output)/filename
        if check:
            if not path.exists() or path.read_text(encoding='utf-8')!=text:
                raise ValueError(f'{path} is stale; regenerate assets')
        else:
            write_if_changed(path,text)
    if Path(output).resolve() == OUTPUT.resolve():
        for name in ('face_assets_manifest.json','face_package.json'):
            path = ROOT / 'service/src/deskbot_server/pb/data' / name
            text = files[name]
            if check:
                if not path.exists() or path.read_text(encoding='utf-8') != text:
                    raise ValueError(f'{path} is stale; regenerate assets')
            else:
                write_if_changed(path, text)
    return bundle


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--source',type=Path,default=SOURCE)
    ap.add_argument('--output',type=Path,default=OUTPUT)
    ap.add_argument('--check',action='store_true',help='fail if generated files differ')
    args=ap.parse_args()
    try:
        b=generate(args.source,args.output,args.check)
    except (ValueError,KeyError,TypeError,OSError) as exc:
        ap.exit(1,f'Expression export failed: {exc}\n')
    print(f'Expressions: {len(b["assets"])}; phonemes: {len(b["phonemes"])}; version={b["version"]}; unique primitives={len(b["primitives"])}; frames={len(b["frames"])}')

if __name__=='__main__':
    main()
